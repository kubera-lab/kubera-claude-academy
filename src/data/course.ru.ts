/** Modules in the chosen language. Quiz answers and ids stay identical, so grading is unchanged. */
export function modulesFor(lang: 'en' | 'ru'): ModuleDef[] {
  if (lang === 'en') return MODULES;
  return MODULES.map((m) => {
    const r = R[m.id];
    return {
      ...m,
      title: r.title,
      objectives: r.objectives,
      lesson: r.lesson,
      practiceTitle: r.practiceTitle,
      practiceIntro: r.practiceIntro,
      quiz: m.quiz.map((q, i) => ({ ...q, prompt: r.quiz[i].prompt, options: r.quiz[i].options, why: r.quiz[i].why })),
    };
  });
}
